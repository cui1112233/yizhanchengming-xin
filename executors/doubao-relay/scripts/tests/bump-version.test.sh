#!/usr/bin/env bash
# scripts/bump-version.sh 的测试:在临时目录里造一份最小仓库(版本号所在的 6 个文件),
# 用 BUMP_ROOT 指向它,断言写入 / 校验行为。真仓库只跑 --check(只读)。
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
BUMP="$REPO/scripts/bump-version.sh"

fails=0
pass() { printf '  ok   %s\n' "$1"; }
fail() { printf '  FAIL %s\n' "$1"; fails=$((fails + 1)); }

assert_eq() { # name expected actual
  if [ "$2" = "$3" ]; then pass "$1"; else fail "$1: expected [$2] got [$3]"; fi
}
assert_contains() { # name haystack needle
  case "$2" in *"$3"*) pass "$1" ;; *) fail "$1: [$2] does not contain [$3]" ;; esac
}

make_fixture() { # dir version
  local d="$1" v="$2"
  mkdir -p "$d/src-tauri" "$d/frontend"
  cat >"$d/src-tauri/Cargo.toml" <<EOF
[package]
name = "doubao-relay"
version = "$v"
edition = "2021"

[dependencies]
tauri = { version = "2", features = [] }
other = { version = "$v" }

[dev-dependencies]
x = "1"
EOF
  cat >"$d/src-tauri/tauri.conf.json" <<EOF
{
  "\$schema": "https://schema.tauri.app/config/2",
  "productName": "doubao-relay",
  "version": "$v",
  "identifier": "com.bwy.doubaorelay",
  "plugins": { "x": { "version": "9.9.9" } }
}
EOF
  cat >"$d/frontend/package.json" <<EOF
{
  "name": "doubao-relay-frontend",
  "private": true,
  "version": "$v",
  "dependencies": { "preact": "^10.0.0" }
}
EOF
  cat >"$d/package.json" <<EOF
{ "name": "doubao-relay-root", "private": true, "version": "$v",
  "scripts": { "dev": "cargo tauri dev" } }
EOF
  cat >"$d/Cargo.lock" <<EOF
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "dlopen2"
version = "$v"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "doubao-relay"
version = "$v"
dependencies = [
 "tauri",
]

[[package]]
name = "doubao-relay-extra"
version = "$v"
EOF
  cat >"$d/README.md" <<EOF
# doubao-relay

![version](https://img.shields.io/badge/version-$v-blue)

Some text mentioning version-$v-elsewhere.
EOF
}

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "bump-version.sh"

# 1. 一致的仓库:--check 打印版本、退出 0
make_fixture "$TMP/a" "0.1.0"
out="$(BUMP_ROOT="$TMP/a" bash "$BUMP" --check)"
assert_eq "check prints current version" "0.1.0" "$out"

# 2. bump 写入全部 6 处,且不碰其它 version 字段
BUMP_ROOT="$TMP/a" bash "$BUMP" 0.2.0 >/dev/null
assert_contains "Cargo.toml [package]" "$(cat "$TMP/a/src-tauri/Cargo.toml")" $'name = "doubao-relay"\nversion = "0.2.0"'
assert_contains "Cargo.toml dependency untouched" "$(cat "$TMP/a/src-tauri/Cargo.toml")" 'other = { version = "0.1.0" }'
assert_contains "tauri.conf.json" "$(cat "$TMP/a/src-tauri/tauri.conf.json")" '"version": "0.2.0"'
assert_contains "tauri.conf.json nested untouched" "$(cat "$TMP/a/src-tauri/tauri.conf.json")" '"version": "9.9.9"'
assert_contains "frontend/package.json" "$(cat "$TMP/a/frontend/package.json")" '"version": "0.2.0"'
assert_contains "root package.json" "$(cat "$TMP/a/package.json")" '"version": "0.2.0"'
assert_contains "Cargo.lock own entry" "$(cat "$TMP/a/Cargo.lock")" $'name = "doubao-relay"\nversion = "0.2.0"'
assert_contains "Cargo.lock other entry untouched" "$(cat "$TMP/a/Cargo.lock")" $'name = "dlopen2"\nversion = "0.1.0"'
assert_contains "Cargo.lock prefix-named entry untouched" "$(cat "$TMP/a/Cargo.lock")" $'name = "doubao-relay-extra"\nversion = "0.1.0"'
assert_contains "Cargo.lock format version untouched" "$(cat "$TMP/a/Cargo.lock")" $'\nversion = 4\n'
assert_contains "README badge" "$(cat "$TMP/a/README.md")" 'badge/version-0.2.0-blue'

# 3. bump 之后 --check 一致;带期望版本时比较
out="$(BUMP_ROOT="$TMP/a" bash "$BUMP" --check)"
assert_eq "check after bump" "0.2.0" "$out"
out="$(BUMP_ROOT="$TMP/a" bash "$BUMP" --check 0.2.0)"
assert_eq "check with matching expected" "0.2.0" "$out"
if BUMP_ROOT="$TMP/a" bash "$BUMP" --check 0.3.0 >/dev/null 2>&1; then
  fail "check with mismatching expected should fail"
else
  pass "check with mismatching expected fails"
fi
# 带 v 前缀的 tag 名也接受
out="$(BUMP_ROOT="$TMP/a" bash "$BUMP" --check v0.2.0)"
assert_eq "check accepts v-prefixed tag" "0.2.0" "$out"

# 4. 不一致:--check 非 0 并点名文件
make_fixture "$TMP/b" "0.1.0"
perl -pi -e 's/"version": "0.1.0"/"version": "0.1.1"/' "$TMP/b/frontend/package.json"
set +e
err="$(BUMP_ROOT="$TMP/b" bash "$BUMP" --check 2>&1 >/dev/null)"
code=$?
set -e
if [ "$code" -ne 0 ]; then pass "inconsistent check fails"; else fail "inconsistent check should fail"; fi
assert_contains "inconsistent check names file" "$err" "frontend/package.json"

# 5. 非法版本号:拒绝且不改任何文件
make_fixture "$TMP/c" "0.1.0"
before="$(cat "$TMP/c/src-tauri/Cargo.toml" "$TMP/c/src-tauri/tauri.conf.json" "$TMP/c/frontend/package.json" "$TMP/c/package.json" "$TMP/c/Cargo.lock" "$TMP/c/README.md")"
# 非数字 / 超过 65535 / 前导零的预发布段:MSI(WiX)不接受,一并拒绝
for bad in "1.2" "v1.2.3" "1.2.3.4" "01.2.3" "abc" "" "0.3.0-rc.1" "0.3.0-beta" "1.2.3-65536" "1.2.3-01"; do
  if BUMP_ROOT="$TMP/c" bash "$BUMP" "$bad" >/dev/null 2>&1; then
    fail "invalid version [$bad] should be rejected"
  else
    pass "invalid version [$bad] rejected"
  fi
done
after="$(cat "$TMP/c/src-tauri/Cargo.toml" "$TMP/c/src-tauri/tauri.conf.json" "$TMP/c/frontend/package.json" "$TMP/c/package.json" "$TMP/c/Cargo.lock" "$TMP/c/README.md")"
assert_eq "invalid version leaves files untouched" "$before" "$after"

# 6. 预发布版本(纯数字):shields 徽章里 '-' 要写成 '--',读回来还原
BUMP_ROOT="$TMP/c" bash "$BUMP" 0.3.0-1 >/dev/null
assert_contains "prerelease badge escaped" "$(cat "$TMP/c/README.md")" 'badge/version-0.3.0--1-blue'
out="$(BUMP_ROOT="$TMP/c" bash "$BUMP" --check)"
assert_eq "prerelease check" "0.3.0-1" "$out"
out="$(BUMP_ROOT="$TMP/c" bash "$BUMP" --check v0.3.0-1)"
assert_eq "prerelease tag check" "0.3.0-1" "$out"
BUMP_ROOT="$TMP/c" bash "$BUMP" 0.3.0-65535 >/dev/null
out="$(BUMP_ROOT="$TMP/c" bash "$BUMP" --check)"
assert_eq "prerelease max 65535" "0.3.0-65535" "$out"
# 非数字预发布 tag(release.yml 的 --check "$TAG")直接拒绝
if BUMP_ROOT="$TMP/c" bash "$BUMP" --check v0.3.0-rc.1 >/dev/null 2>&1; then
  fail "check with non-numeric prerelease tag should fail"
else
  pass "check with non-numeric prerelease tag fails"
fi
# 从预发布再 bump 回正式版
BUMP_ROOT="$TMP/c" bash "$BUMP" 0.3.0 >/dev/null
out="$(BUMP_ROOT="$TMP/c" bash "$BUMP" --check)"
assert_eq "prerelease -> release" "0.3.0" "$out"

# 7. README 没有徽章也能用(只校验 / 写入其余 5 处)
make_fixture "$TMP/d" "0.1.0"
printf '# no badge\n' >"$TMP/d/README.md"
BUMP_ROOT="$TMP/d" bash "$BUMP" 0.4.0 >/dev/null
out="$(BUMP_ROOT="$TMP/d" bash "$BUMP" --check)"
assert_eq "no badge still works" "0.4.0" "$out"

# 8. 缺文件:报错
make_fixture "$TMP/e" "0.1.0"
rm "$TMP/e/src-tauri/tauri.conf.json"
if BUMP_ROOT="$TMP/e" bash "$BUMP" --check >/dev/null 2>&1; then
  fail "missing file should fail"
else
  pass "missing file fails"
fi

# 8b. 文件在但某处版本号读不到:bump 拒绝,且不留半截修改
make_fixture "$TMP/f" "0.1.0"
perl -0pi -e 's/name = "doubao-relay"\nversion/name = "doubao-relay"\nversionx/' "$TMP/f/Cargo.lock"
before="$(cat "$TMP/f/src-tauri/Cargo.toml" "$TMP/f/src-tauri/tauri.conf.json" "$TMP/f/frontend/package.json" "$TMP/f/package.json" "$TMP/f/Cargo.lock" "$TMP/f/README.md")"
set +e
err="$(BUMP_ROOT="$TMP/f" bash "$BUMP" 0.2.0 2>&1 >/dev/null)"
code=$?
set -e
if [ "$code" -ne 0 ]; then pass "unreadable version fails bump"; else fail "unreadable version should fail bump"; fi
assert_contains "unreadable version names file" "$err" "Cargo.lock"
after="$(cat "$TMP/f/src-tauri/Cargo.toml" "$TMP/f/src-tauri/tauri.conf.json" "$TMP/f/frontend/package.json" "$TMP/f/package.json" "$TMP/f/Cargo.lock" "$TMP/f/README.md")"
assert_eq "unreadable version leaves files untouched" "$before" "$after"

# 8c. CRLF 换行(Windows runner 上 core.autocrlf=true 的 checkout):--check / bump 都要能用,且保留 CRLF
make_fixture "$TMP/g" "0.1.0"
for f in src-tauri/Cargo.toml src-tauri/tauri.conf.json frontend/package.json package.json Cargo.lock README.md; do
  perl -pi -e 's/\n/\r\n/' "$TMP/g/$f"
done
out="$(BUMP_ROOT="$TMP/g" bash "$BUMP" --check)"
assert_eq "crlf check" "0.1.0" "$out"
BUMP_ROOT="$TMP/g" bash "$BUMP" 0.2.0 >/dev/null
out="$(BUMP_ROOT="$TMP/g" bash "$BUMP" --check v0.2.0)"
assert_eq "crlf bump" "0.2.0" "$out"
assert_contains "crlf Cargo.lock entry bumped, CRLF kept" "$(cat "$TMP/g/Cargo.lock")" $'name = "doubao-relay"\r\nversion = "0.2.0"\r\n'
assert_contains "crlf Cargo.toml bumped, CRLF kept" "$(cat "$TMP/g/src-tauri/Cargo.toml")" $'version = "0.2.0"\r\n'

# 9. 用法错误
if bash "$BUMP" >/dev/null 2>&1; then fail "no args should fail"; else pass "no args fails"; fi

# 10. 真仓库:只读校验,各处一致
out="$(bash "$BUMP" --check)"
case "$out" in
  [0-9]*.[0-9]*.[0-9]*) pass "real repo consistent ($out)" ;;
  *) fail "real repo check printed [$out]" ;;
esac

if [ "$fails" -ne 0 ]; then
  echo "bump-version.sh: $fails failure(s)"
  exit 1
fi
echo "bump-version.sh: all passed"
